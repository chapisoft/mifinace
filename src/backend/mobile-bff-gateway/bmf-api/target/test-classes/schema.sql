    Max_Retries INT NOT NULL DEFAULT 5,
    Error_Message VARCHAR(500) NULL,
    Created_Time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    Processed_Time TIMESTAMP NULL,
    Sent_Time TIMESTAMP NULL
);

