CREATE SCHEMA IF NOT EXISTS dbo;

-- 1. Bảng SYS_MOBILE_DEVICE
CREATE TABLE IF NOT EXISTS dbo.SYS_MOBILE_DEVICE (
    Device_ID VARCHAR(64) NOT NULL,
    User_ID VARCHAR(32) NOT NULL,
    User_Type VARCHAR(16) NOT NULL,
    Platform VARCHAR(16) NOT NULL,
    Device_Name VARCHAR(128) NULL,
    OS_Version VARCHAR(32) NULL,
    App_Version VARCHAR(16) NOT NULL,
    Push_Token VARCHAR(256) NULL,
    Public_Key VARCHAR(512) NULL,
    Is_Active INT NOT NULL DEFAULT 1,
    Last_Active_Time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    Created_Time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    Updated_Time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (Device_ID, User_ID)
);

-- 2. Bảng SYS_OUTBOX_EVENT
CREATE TABLE IF NOT EXISTS dbo.SYS_OUTBOX_EVENT (
    Event_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Aggregate_Type VARCHAR(32) NOT NULL,
    Aggregate_ID VARCHAR(64) NOT NULL,
    Event_Type VARCHAR(64) NOT NULL,
    Payload_JSON CLOB NOT NULL,
    Status VARCHAR(16) NOT NULL DEFAULT 'PENDING',
